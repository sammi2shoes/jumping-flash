package com.jumpingflash.ax12;

import static org.junit.Assert.*;

import java.util.*;
import org.junit.Test;

public class UmbusProbeTest {
  static byte[] candidate(int sync, int s2) {
    int header = sync == 0xa7 ? 6 : 5;
    byte[] b = new byte[header + 94];
    b[0] = (byte) sync;
    b[1] = (byte) b.length;
    if (sync == 0xa7) b[2] = 0;
    int route = sync == 0xa7 ? 3 : 2;
    b[route] = 0x10;
    b[route + 1] = 2;
    b[route + 2] = 4;
    b[header] = 1;
    int off = header + 1 + 13 * 2;
    b[off] = (byte) s2;
    b[off + 1] = (byte) (s2 >> 8);
    b[b.length - 1] = (byte) UmbusProbe.crc8(b, 1, b.length - 1);
    return b;
  }

  @Test
  public void crcGoldenVector() {
    byte[] b = "123456789".getBytes();
    assertEquals(0xa1, UmbusProbe.crc8(b, 0, b.length));
  }

  @Test
  public void publishedLegacyCaptureIsAcceptedButNotMislabelledAsSeptSources() {
    // Independent ax12-research protocol example, not generated by our encoder.
    String hex =
        "a657100204010300ffffb8fe0100f8ff9c0000800080008000800080008007007bfe0080008000800080008000800cfe0cfe00000cfe0000f4010080008000800080008000800080008000800cfe000000000100910144";
    byte[] data = new byte[hex.length() / 2];
    for (int n = 0; n < data.length; n++)
      data[n] = (byte) Integer.parseInt(hex.substring(n * 2, n * 2 + 2), 16);
    UmbusProbe p = new UmbusProbe();
    p.feed(data, data.length, 100);
    assertEquals(87, data.length);
    assertEquals(1, p.crcFrames);
    assertEquals(0, p.channelCandidates);
    assertNull(p.sources);
  }

  @Test
  public void arbitraryFragmentsDecodeBothEnvelopeLengths() {
    for (int sync : new int[] {0xa6, 0xa7}) {
      byte[] b = candidate(sync, -321);
      for (int chunk : new int[] {1, 3, 17, 512}) {
        UmbusProbe p = new UmbusProbe();
        for (int n = 0; n < b.length; n += chunk) {
          byte[] part = Arrays.copyOfRange(b, n, Math.min(n + chunk, b.length));
          p.feed(part, part.length, 123);
        }
        assertEquals(1, p.crcFrames);
        assertEquals(1, p.channelCandidates);
        assertEquals(-321, p.sources[13]);
        assertEquals(123, p.lastCandidateAt);
      }
    }
  }

  @Test
  public void badCrcAndNoiseRecoverWithoutFreshness() {
    UmbusProbe p = new UmbusProbe();
    byte[] bad = candidate(0xa6, 12);
    bad[20] ^= 1;
    p.feed(new byte[] {0, 1, 2, 3}, 4, 10);
    p.feed(bad, bad.length, 20);
    assertEquals(0, p.channelCandidates);
    byte[] good = candidate(0xa6, 123);
    p.feed(good, good.length, 30);
    assertEquals(1, p.channelCandidates);
    assertEquals(30, p.lastCandidateAt);
    assertTrue(p.badFrames > 0);
  }

  @Test
  public void oldOrWrongRouteFramesNeverClaimCurrentInputs() {
    byte[] b = candidate(0xa6, 12);
    b[3] = 4;
    b[b.length - 1] = (byte) UmbusProbe.crc8(b, 1, b.length - 1);
    UmbusProbe p = new UmbusProbe();
    p.feed(b, b.length, 10);
    assertEquals(1, p.frames);
    assertEquals(0, p.channelCandidates);
    assertNull(p.sources);
    assertEquals(0, p.lastCandidateAt);
  }

  @Test
  public void xorFallbackIsLoggedButNotTrustedForSources() {
    byte[] b = candidate(0xa6, 123);
    int xor = 0;
    for (int i = 1; i < b.length - 1; i++) xor ^= b[i] & 255;
    if (xor == UmbusProbe.crc8(b, 1, b.length - 1)) {
      b[20] ^= 2;
      xor = 0;
      for (int i = 1; i < b.length - 1; i++) xor ^= b[i] & 255;
    }
    b[b.length - 1] = (byte) xor;
    UmbusProbe p = new UmbusProbe();
    p.feed(b, b.length, 10);
    assertEquals(1, p.xorFrames);
    assertEquals(0, p.channelCandidates);
    assertEquals(0, p.lastCandidateAt);
  }

  @Test
  public void repeatedReportsRefreshOnlySourceFrames() {
    UmbusProbe p = new UmbusProbe();
    byte[] b = candidate(0xa6, 0);
    p.feed(b, b.length, 10);
    p.feed(b, b.length, 50);
    assertEquals(2, p.channelCandidates);
    assertEquals(50, p.lastCandidateAt);
    assertTrue(p.describe(300).contains("age=250 ms"));
  }

  @Test
  public void nonsensicalLengthsDoNotGrowBufferOrExposeInputs() {
    UmbusProbe p = new UmbusProbe();
    byte[] b = new byte[8000];
    Arrays.fill(b, (byte) 0xa7);
    p.feed(b, b.length, 1);
    assertNull(p.sources);
    assertTrue(p.badFrames > 0);
  }
}
